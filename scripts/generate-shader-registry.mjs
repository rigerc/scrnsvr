import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve('src/renderer/shaders');
const folders = (await readdir(root, { withFileTypes: true }))
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort();
const entries = [];
for (const folder of folders) {
  const manifestPath = path.join(root, folder, 'manifest.ts');
  const shaderPath = path.join(root, folder, 'shader.glsl');
  const source = await readFile(manifestPath, 'utf8');
  await readFile(shaderPath);
  const match = source.match(/export\s+const\s+([A-Za-z_$][\w$]*)\s*=/);
  if (!match) throw new Error(`${manifestPath} must export one manifest constant`);
  entries.push({ folder, symbol: match[1] });
}
const imports = entries.flatMap(({ folder, symbol }, index) => [
  `import { ${symbol} } from './${folder}/manifest';`,
  `import shader${index} from './${folder}/shader.glsl';`,
]);
const properties = entries.map(({ symbol }, index) => `  [${symbol}.id]: { manifest: ${symbol}, source: shader${index} },`);
const generated = `// Generated by scripts/generate-shader-registry.mjs. Do not edit by hand.\n${imports.join('\n')}\n\nexport const shaderRegistry: Record<string, { manifest: import('../../shared/manifest').ShaderManifest; source: string }> = {\n${properties.join('\n')}\n};\nexport const shaderIds = Object.keys(shaderRegistry);\n`;
await writeFile(path.join(root, 'generated.ts'), generated, 'utf8');
