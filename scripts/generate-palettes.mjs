// Generate src/shared/palettes.generated.ts from reference/*.yml.
// Fixes the 30 curated palettes at build time so the app never reads reference/.
import { writeFile } from 'node:fs/promises';
import path from 'node:path';
import { palettes as curated } from './palettes.config.mjs';
import { buildPalette } from './lib/palettes.mjs';

const referenceDir = path.resolve('reference');
const outputPath = path.resolve('src/shared/palettes.generated.ts');

const palettes = curated.map((entry) => buildPalette(entry, referenceDir));

const header = `// Generated by scripts/generate-palettes.mjs from reference/*.yml. Do not edit by hand.
export type PaletteVariant = 'dark' | 'light';
export interface ColorRoles { surface: string; onSurface: string; primary: string; secondary: string; tertiary: string; }
export interface Palette {
  id: string;
  name: string;
  variant: PaletteVariant;
  background: string;
  foreground: string;
  cursor?: string;
  /** ANSI 0-15: index 0 is color_01. */
  ansi: string[];
  roles: ColorRoles;
}
`;
const body = `export const palettes: Palette[] = ${JSON.stringify(palettes, null, 2)};\n`;
await writeFile(outputPath, `${header}\n${body}`, 'utf8');
console.log(`Wrote ${palettes.length} palettes to ${path.relative(process.cwd(), outputPath)}`);
